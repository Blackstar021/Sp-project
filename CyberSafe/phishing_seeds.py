"""Fictional, non-clickable scenarios for the student phishing lab."""

ACTION_OPTIONS = [
    "Pause; verify using a known official channel before acting.",
    "Report the message to the platform or school contact.",
    "Tell a trusted adult or teacher and ask for help.",
    "Do not click or reply; delete or block it if appropriate.",
    "If you entered a password, change it through the official site and tell a trusted adult.",
]


def _scenario(
    scenario_type,
    difficulty,
    interaction_type,
    sender,
    subject,
    body,
    is_phishing,
    explanation,
    correct_action,
    *,
    red_flags=(),
    parts=(),
    prompt="Phishing or legitimate?",
    options=(),
    link_text="",
    link_destination="",
):
    answer_options = list(options) if interaction_type == "action" else ["Phishing", "Legitimate"]
    if interaction_type == "spot":
        correct_answer = [
            index
            for index, (label, _text) in enumerate(parts)
            if label in red_flags
        ]
    else:
        correct_text = (
            correct_action
            if interaction_type == "action"
            else "Phishing" if is_phishing else "Legitimate"
        )
        correct_answer = answer_options.index(correct_text)
    return {
        "type": scenario_type,
        "difficulty": difficulty,
        "interaction_type": interaction_type,
        "sender": sender,
        "subject": subject,
        "body": body,
        "is_phishing": is_phishing,
        "red_flags": list(red_flags),
        "explanation": explanation,
        "correct_action": correct_action,
        "correct_answer": correct_answer,
        "prompt": prompt,
        "options": answer_options,
        "clue_parts": [{"label": label, "text": text} for label, text in parts],
        "link_text": link_text,
        "link_destination": link_destination,
    }


